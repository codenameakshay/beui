import {chromium} from '/tmp/beui-parity-capture-runtime/node_modules/playwright-core/index.mjs';
import {mkdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const out=process.argv[2];await mkdir(out);
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:1400}});
const log={requests:[],failed:[],responses:[],console:[],errors:[]};const reads=[];
page.on('request',r=>log.requests.push(r.url()));
page.on('requestfailed',r=>log.failed.push({url:r.url(),failure:r.failure()}));
page.on('console',m=>log.console.push({type:m.type(),text:m.text()}));
page.on('pageerror',e=>log.errors.push(String(e)));
page.on('response',r=>{if(/font|ttf|otf|main.dart.js/i.test(r.url()))reads.push(r.body().then(b=>log.responses.push({url:r.url(),status:r.status(),bytes:b.length,sha256:createHash('sha256').update(b).digest('hex')})).catch(e=>log.responses.push({url:r.url(),error:String(e)})));});
await page.goto('http://127.0.0.1:18118/?slug=signup-form&theme=light&previewWidth=592&captureProbe=1');
await page.waitForFunction(()=>!!globalThis.__beuiCapture);
await page.waitForTimeout(10000);await page.screenshot({path:out+'/native.png'});
await page.locator('flt-semantics-placeholder').evaluate(e=>e.click());
await page.waitForTimeout(1000);await page.screenshot({path:out+'/semantics.png'});
await Promise.all(reads);await writeFile(out+'/network.json',JSON.stringify(log,null,2));
await browser.close();

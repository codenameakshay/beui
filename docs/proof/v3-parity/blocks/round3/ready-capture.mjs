import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';

const root = import.meta.dirname;
const output = path.join(root, process.argv[2]);
const recorder = '/Users/codenameakshay/.t3/worktrees/beui/t3-f7137276/tool/parity_capture.mjs';
const observer = path.join(root, 'font-observer.mjs');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const expected = process.env.EXPECTED_JS_SHA256;
assert(expected);
const url = 'http://127.0.0.1:8108/main.dart.js';
const actual = sha(Buffer.from(await (await fetch(url)).arrayBuffer()));
assert.equal(actual, expected);
await mkdir(output);
const config = JSON.parse(await readFile(path.join(root, '../round2/press-reduced/candidate-dark-reduce-config.json')));
config.servedJs = { url, sha256: expected, revision: process.env.BUILD_REVISION };
config.provenance.fontObserverSha256 = sha(await readFile(observer));
config.provenance.note = 'Original press-reduced recording retained. This run observes actual font response bodies before first screenshot. Decoded glyph inspection remains required.';
await writeFile(path.join(output, 'served-build.json'), JSON.stringify({ expected, actual, checkedAt: new Date().toISOString(), recorderSha256: sha(await readFile(recorder)), observerSha256: config.provenance.fontObserverSha256 }, null, 2));
const file = path.join(output, 'config.json');
await writeFile(file, JSON.stringify(config, null, 2));
const run = spawnSync(process.execPath, [recorder, file, path.join(output, 'recording')], { env: { ...process.env, PARITY_PLAYWRIGHT: observer, FONT_PROOF_FILE: path.join(output, 'font-responses.json') }, encoding: 'utf8', timeout: 180000 });
await writeFile(path.join(output, 'record.log'), `${run.stdout}\n${run.stderr}\nexit=${run.status}\n`);
assert.equal(run.status, 0);
